def draw_char(display, char, x, y, color, scale=1):
    """Draw a single character at position (x, y) with optional scaling."""
    if char not in _FONT_DATA:
        char = '?'

    width, bitmap = _FONT_DATA[char]

    for row_idx in range(FONT_HEIGHT):
        if row_idx >= len(bitmap):
            break
        row = bitmap[row_idx]
        for col in range(width):
            if row & (0x80 >> col):
                if scale == 1:
                    display.pixel(x + col, y + row_idx, color)
                else:
                    display.fill_rect(
                        x + col * scale,
                        y + row_idx * scale,
                        scale, scale, color
                    )

    return width * scale + CHAR_SPACING * scale


def draw_text(display, text, x, y, color, scale=1):
    """Draw a string of text, returns total width drawn."""
    cx = x
    for char in text:
        w = draw_char(display, char, cx, y, color, scale)
        cx += w
    return cx - x


def measure_text(text, scale=1):
    """Measure the pixel width of a text string."""
    total = 0
    for char in text:
        if char in _FONT_DATA:
            width = _FONT_DATA[char][0]
        else:
            width = _FONT_DATA['?'][0]
        total += width * scale + CHAR_SPACING * scale
    return total - CHAR_SPACING * scale if text else 0


def text_height(scale=1):
    """Return the height of text at given scale."""
    return FONT_HEIGHT * scale
